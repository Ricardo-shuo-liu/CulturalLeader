def city_events(name: str) -> dict:
    """返回某座精选城市的 headline 与事件列表（按年份升序）。"""

    entry = EVENTS.get(name) or {}
    events = sorted(entry.get("events") or [], key=lambda item: item[0])
    return {
        "headline": entry.get("headline") or "",
        "events": [
            {"year": int(year), "title": title, "text": text, "narration": narration}
            for year, title, text, narration in events
        ],
    }
